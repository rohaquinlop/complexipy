#!/usr/bin/env bash
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
TOOLS_DIR="${TOOLS_DIR:-$HOME/.cache/complexipy-benchmarks/competitors}"
DJANGO="$REPO_ROOT/benchmarks/corpus/django"
NEW_CLI="$REPO_ROOT/.venv/bin/complexipy"
RESULTS_FILE="$REPO_ROOT/benchmarks/competitors.md"
THRESHOLD=15
RUNS="${RUNS:-5}"
WARMUP="${WARMUP:-1}"

FLAKE8_PINS="flake8==7.5.0 flake8-cognitive-complexity==0.1.0"
PYLINT_PINS="pylint==4.1.3 pylint-cognitive-complexity==0.1.1"

fail() {
    echo "error: $1" >&2
    exit 1
}

for tool in hyperfine uv; do
    command -v "$tool" >/dev/null 2>&1 || fail "$tool is required"
done
[[ -x "$NEW_CLI" ]] || fail "$NEW_CLI is missing; run: uv run maturin develop --release"
[[ -d "$DJANGO/.git" ]] || fail "$DJANGO is missing; run benchmarks/benchmark-cli.sh first to clone the corpus"

provision() {
    local name="$1"
    shift
    local venv="$TOOLS_DIR/$name"
    if [[ ! -x "$venv/bin/python" ]]; then
        uv venv --quiet --python 3.12 "$venv"
    fi
    uv pip install --quiet --python "$venv/bin/python" "$@"
}

echo "== provisioning =="
provision flake8 flake8==7.5.0 flake8-cognitive-complexity==0.1.0
provision pylint pylint==4.1.3 pylint-cognitive-complexity==0.1.1
new_version="$("$NEW_CLI" --version 2>&1 | head -1 | awk '{print $2}')"
echo "  complexipy $new_version, $FLAKE8_PINS, $PYLINT_PINS"

workdir="$(mktemp -d)"
trap 'rm -rf "$workdir"' EXIT
cd "$workdir"

echo "== timing django ($(find "$DJANGO" -name '*.py' -not -path '*/.git/*' | wc -l | tr -d ' ') files) =="
hyperfine \
    --warmup "$WARMUP" \
    --runs "$RUNS" \
    --style basic \
    --ignore-failure \
    --export-json "$workdir/hyperfine.json" \
    -n "complexipy $new_version" \
    "$NEW_CLI $DJANGO --max-complexity-allowed $THRESHOLD" \
    -n "flake8-cognitive-complexity 0.1.0" \
    "$TOOLS_DIR/flake8/bin/flake8 --isolated --select CCR001 --max-cognitive-complexity $THRESHOLD $DJANGO" \
    -n "pylint-cognitive-complexity 0.1.1" \
    "$TOOLS_DIR/pylint/bin/pylint --rcfile=/dev/null --recursive=y --load-plugins pylint_cognitive_complexity --disable=all --enable=too-cognitively-complex --max-cognitive-complexity=$THRESHOLD $DJANGO"

"$REPO_ROOT/.venv/bin/python" "$REPO_ROOT/benchmarks/render_competitor_chart.py" \
    "$workdir/hyperfine.json" "$RESULTS_FILE" "$REPO_ROOT/docs/img" "$REPO_ROOT/docs/es/img"

{
    echo "<!-- Generated by benchmarks/benchmark-competitors.sh. Do not edit. -->"
    echo
    echo "- Machine: $(sysctl -n hw.model 2>/dev/null || uname -m), $(sysctl -n machdep.cpu.brand_string 2>/dev/null || echo unknown CPU)"
    echo "- django @ $(git -C "$DJANGO" rev-parse HEAD)"
    echo "- complexipy $new_version built from $(git -C "$REPO_ROOT" rev-parse --short HEAD); $FLAKE8_PINS; $PYLINT_PINS"
    echo "- hyperfine warmup=$WARMUP runs=$RUNS, threshold $THRESHOLD for every tool, each tool with its default parallelism"
    echo "- Date: $(date +%Y-%m-%d)"
    echo
    cat "$RESULTS_FILE"
} >"$workdir/competitors.md"
mv "$workdir/competitors.md" "$RESULTS_FILE"

echo "== results written to $RESULTS_FILE and docs/img/competitors-{light,dark}.svg =="
